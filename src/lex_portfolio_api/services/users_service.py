from sqlalchemy.orm import Session

from lex_portfolio_api.models.users import User
from lex_portfolio_api.schemas.users import UserCreate

from lex_portfolio_api.core.security import hash_password, verify_password


def get_user_by_email(db: Session, email: str) -> User | None:
    return db.query(User).filter(User.email == email).first()


def get_user_by_id(db: Session, user_id: int) -> User | None:
    return db.query(User).filter(User.id == user_id).first()


def create_user(db: Session, user_schema: UserCreate) -> User:
    new_user = User(
        email=user_schema.email, hashed_password=hash_password(user_schema.password)
    )

    db.add(new_user)
    db.commit()
    db.refresh(new_user)

    return new_user


def authenticate_user(db: Session, email: str, password: str) -> User | None:
    user = get_user_by_email(db, email)

    if user is None:
        return None

    if not verify_password(password, user.hashed_password):
        return None

    return user
